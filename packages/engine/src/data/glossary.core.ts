/** seluruh kamus yang dipakai serving: frasa riset lama + inti authored + batch 2 */
export const GLOSSARY_CORE: GlossaryRow[] = [...ID_EN, ...GLOSSARY_AUTHORED, ...GLOSSARY_BATCH2];

/**
 * Susun akhir untuk PhraseBook: core → gen → overrides. Override menang, dan kunci
 `id#sense` membuat varian kedua sebuah kata hidup berdampingan, bukan saling timpa.
 */
export function mergedGlossary(): GlossaryRow[] {
  const byKey = new Map<string, GlossaryRow>();
  for (const row of [...GLOSSARY_CORE, ...GLOSSARY_GEN, ...GLOSSARY_OVERRIDES]) {
    const key = `${normalize(row[0])}#${row[3]?.sense ?? 1}`;
    byKey.set(key, row);
  }
  return [...byKey.values()].sort((a, b) => b[2] - a[2]);
}
